"""Synthetic messy corpus with exact ground truth. Seeded, reproducible.

90 cases: 30 invoice / 30 resume / 30 PII. Mess axes: label variants, date/
currency formats, case noise, junk lines, missing fields, order swaps,
overlap traps, decoys, multi-page. Truth recorded at generation.
"""
from __future__ import annotations

import json
import random
from pathlib import Path

import fitz

rng = random.Random(20261111)
OUT = Path("samples/corpus")
OUT.mkdir(parents=True, exist_ok=True)

FIRST = ["Jane", "John", "Amara", "Priya", "Carlos", "Mei", "Omar", "Sofia", "Liam", "Aisha"]
LAST = ["Doe", "Smith", "Okafor", "Sharma", "Ruiz", "Chen", "Haddad", "Rossi", "Novak", "Khan"]
CO = ["Acme Corp", "Globex Ltd", "Initech", "Umbrella Co", "Hooli", "Stark Industries",
      "Wayne Enterprises", "Massive Dynamic", "Soylent Co", "Tyrell Corp"]
TITLE = ["Senior Engineer", "Junior Dev", "Product Manager", "Data Analyst", "DevOps Lead"]
SKILL = ["Python", "Rust", "Postgres", "Kubernetes", "TypeScript", "Go", "AWS", "Figma"]

INV_NO = ["Invoice Number", "Invoice #", "Invoice No", "INV", "Ref", "Reference No", "Bill No"]
INV_DT = ["Invoice Date", "Date of Issue", "Dated", "Issued", "Billing Date"]
DUE_LB = ["Due Date", "Payment Due", "Pay By", "Due On", "Net Terms"]
TOT_LB = ["Total Due", "Grand Total", "Amount Due", "Total Amount", "Balance Due"]
TAX_LB = ["Tax", "VAT", "GST", "Sales Tax", "VAT Included"]

SEC_EXP = ["Experience", "Work History", "Employment", "Professional Experience", "Career"]
SEC_EDU = ["Education", "Qualifications", "Academic Background", "Degrees"]
SEC_SKL = ["Skills", "Technical Skills", "Core Competencies"]

JUNK = ["Thank you for your business!", "*** CONFIDENTIAL ***", "Page 1 of 1",
        "Generated by ERP v4.2", "Questions? Call support.", "---", "E&OE"]


def _pdf(lines_per_page: list[list[str]], name: str) -> str:
    doc = fitz.open()
    for lines in lines_per_page:
        page = doc.new_page()
        y = 72
        for ln in lines:
            page.insert_text((72, y), ln)
            y += 15
    path = str(OUT / name)
    doc.save(path)
    return path


def _noise(lines: list[str], case_odds=0.15, junk_odds=0.25) -> list[str]:
    out = []
    for ln in lines:
        r = rng.random()
        if r < case_odds / 2:
            ln = ln.upper()
        elif r < case_odds:
            ln = ln.lower()
        out.append(ln)
        if rng.random() < junk_odds:
            out.append(rng.choice(JUNK))
    rng.shuffle(out) if rng.random() < 0.1 else None
    return ["  " + ln if rng.random() < 0.2 else ln for ln in out]


def _money(fmt: int, cents: str) -> str:
    return ["$1,240.00", "EUR 2,310.50", "2,310.50 EUR", "£899.99"][fmt % 4].replace(
        "1,240.00", cents).replace("2,310.50", cents).replace("899.99", cents)


def gen_invoice(i: int) -> dict:
    no = f"{rng.choice(['INV', 'GB', 'REF'])}-{rng.randint(1000, 9999)}{rng.choice(['', '/X', '-A'])}"
    seller, buyer = rng.sample(CO, 2)
    d = f"{rng.randint(1, 28):02d}"
    dates = [f"2026-03-{d}", f"{d}.03.2026", f"03/{d}/2026"]
    df = rng.randrange(3)
    cur = rng.randrange(4)
    total = _money(cur, f"{rng.randint(100, 9000)},{rng.randint(10, 99)}")
    tax = _money(cur, f"{rng.randint(10, 500)}.{rng.randint(10, 99):02d}")
    lines = [seller, f"{rng.choice(INV_NO)}: {no}",
             f"{rng.choice(INV_DT)} {dates[df]}"]
    has_buyer = rng.random() < 0.8
    if has_buyer:
        lines.append(f"Bill To: {buyer}")
    else:
        buyer = None  # no bill-to in doc: model must return null, not invent
    if rng.random() > 0.2:
        due = dates[(df + 1) % 3]
        lines.append(f"{rng.choice(DUE_LB)} {due}")
        exp["due_date"] = due
    else:
        exp["due_date"] = None
    lines.append(f"{rng.choice(TOT_LB)} {total}")
    exp["total_amount"] = total
    if rng.random() > 0.25:
        lines.append(f"{rng.choice(TAX_LB)} {tax}")
        exp["tax_amount"] = tax
    else:
        exp["tax_amount"] = None
    exp.update({"seller": seller, "buyer": buyer, "line_items": None})  # llm-scored, presence only
    pages = [_noise(lines)]
    if rng.random() < 0.15:  # 2-page: totals pushed to page 2
        pages = [_noise(lines[:2]), _noise(lines[2:])]
    return {"id": f"inv_{i:03d}", "pack": "invoice",
            "pdf": _pdf(pages, f"inv_{i:03d}.pdf"), "expected": exp}


def gen_resume(i: int) -> dict:
    name = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
    email = f"{name.lower().replace(' ', '.')}@example.com"
    phone = f"+1 555-{rng.randint(100, 999)}-{rng.randint(1000, 9999)}"
    t1, t2 = rng.sample(TITLE, 2)
    c1, c2 = rng.sample(CO, 2)
    skills = ", ".join(rng.sample(SKILL, 3))
    sections = [
        (rng.choice(SEC_EXP), [f"{t1} at {c1} (2021-2026)", f"{t2} at {c2} (2019-2021)"]),
        (rng.choice(SEC_EDU), [f"BSc Computer Science, MIT 2019"]),
    ]
    if rng.random() < 0.7:
        order = rng.sample([0, 1], 2)
    else:
        order = [0, 1]
    lines = [name, email, f"Phone: {phone}", ""]
    exp = {"name": name, "email": email, "phone": phone, "current_title": t1,
           "skills": skills, "experience": None, "education": None}  # sections: body-line check
    bodies = {}
    for idx in order:
        h, body = sections[idx]
        lines += ["", h, *body]
        bodies[h] = body
    if rng.random() < 0.7:
        lines += ["", rng.choice(SEC_SKL), skills]
    else:
        exp["skills"] = None  # no section in doc: truth is null, model must not invent
    lines = _noise([ln for ln in lines if ln != "" or rng.random() < 0.3], junk_odds=0.15)
    exp["_bodies"] = bodies
    return {"id": f"res_{i:03d}", "pack": "resume",
            "pdf": _pdf([lines], f"res_{i:03d}.pdf"), "expected": exp}


def gen_pii(i: int) -> dict:
    email = f"user{i}@example.com"
    phone = f"+1 555-{rng.randint(100, 999)}-{rng.randint(1000, 9999)}"
    ssn = f"{rng.randint(100, 999)}-{rng.randint(10, 99)}-{rng.randint(1000, 9999)}"
    card = "4111 1111 1111 1111"
    iban = f"GB{rng.randint(10, 99)}NWBK60161331926819"
    n_mail = rng.randint(1, 3)
    lines = [f"Contact: {email}"]
    exp_m = {"email": [email] * n_mail, "phone": [phone]}
    for _ in range(n_mail - 1):
        lines.append(f"CC: {email}")
    lines.append(f"Call {phone}")
    if rng.random() < 0.8:
        lines.append(f"SSN: {ssn}")
        exp_m["ssn"] = [ssn]
    if rng.random() < 0.7:
        lines.append(f"Card {card}")
        exp_m["credit_card"] = [card]
    if rng.random() < 0.6:
        lines.append(f"IBAN {iban}")
        exp_m["iban"] = [iban]
    if rng.random() < 0.3:  # decoy: short order id, must NOT match card
        lines.append(f"Order 12345 confirmed")
    lines = _noise(lines, case_odds=0.0, junk_odds=0.2)
    pages = [lines]
    if rng.random() < 0.3:
        pages = [lines[:len(lines) // 2], lines[len(lines) // 2:]]
    return {"id": f"pii_{i:03d}", "pack": "pii",
            "pdf": _pdf(pages, f"pii_{i:03d}.pdf"),
            "expected": {k: sorted(v) for k, v in exp_m.items()}}


def main(n_each: int = 30):
    cases = []
    for i in range(n_each):
        cases.append(gen_invoice(i))
        cases.append(gen_resume(i))
        cases.append(gen_pii(i))
    with open(OUT / "corpus.jsonl", "w") as f:
        for c in cases:
            f.write(json.dumps(c) + "\n")
    print(f"wrote {len(cases)} cases to {OUT}")


if __name__ == "__main__":
    main()
